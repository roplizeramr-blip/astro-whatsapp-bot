    if (game) {
      return m.reply(`🎭 فيه لعبة شغالة في الشات!\n🔍 التلميح: *${hintAt(game, game.tries)}*\nاكتب تخمينك: \`.guesswho guess اسم الشخصية\``);
    }

    // اختيار شخصية جديدة
    const pick = PEOPLE[Math.floor(Math.random() * PEOPLE.length)];
    all[m.jid] = { who: pick.who, hints: pick.hints, tries: 0, by: m.identityKey ?? m.sender, at: Date.now() };
    db.set('guessWho', all);

